static int compare_name(const void *l, const void *r) {
    const struct hidpp_name *_l = l, *_r = r;
    return _l->id - _r->id;
}

const char *hidpp_feature_name(uint16_t index) {
    struct hidpp_name *feat = bsearch(
        &index,
        features,
        sizeof(features) / sizeof(*features),
        sizeof(*features),
        compare_name
    );

    return feat ? feat->name : "Unknown HID++ feature";
}

const char *hidpp_keymap_name(uint16_t feature) {
    struct hidpp_name *control = bsearch(
        &index,
        controls,
        sizeof(controls) / sizeof(*controls),
        sizeof(*controls),
        compare_name
    );

    return control ? control->name : "Unknown HID++ button";
}

int hidpp_keymap_from_name(const char *name) {
    if (!name)
        return 0;

    for (size_t i = 0; controls[i].id; i++)
        if (0 == strcmp(controls[i].name, name))
            return controls[i].id;

    return 0;
}
